let LANG = 'fr';

// « auto » : langue de l'interface de Premiere (fr_FR, en_US…) ; anglais pour toute autre langue que le français
function detectLanguage(choice) {
  if (choice === 'fr' || choice === 'en') return choice;
  try {
    const env = JSON.parse(window.__adobe_cep__.getHostEnvironment());
    return /^fr/i.test(env.appUILocale || '') ? 'fr' : 'en';
  } catch (e) {
    return 'fr';
  }
}

function t(key, vars) {
  const text = (I18N[LANG] && I18N[LANG][key]) || I18N.fr[key] || key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars && name in vars ? vars[name] : m));
}

// Textes fixes du panneau : data-i18n (contenu), data-i18n-title (info-bulle)
function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
